"""The shared models folder without Stability Matrix: Comfy Desktop's default models folder
(ComfyUI's own folder names), a missing SM-named folder never chosen, and a folder set by hand."""
import os
import shutil
import sys
import tempfile
import types

import test_shared as T

check = T.check


def main():
    base, user = T.fake_install("DesktopRoot")
    os.remove(os.path.join(base, "extra_model_paths.yaml"))  # no Stability Matrix config in this install
    shared = tempfile.mkdtemp(prefix="smf_desktop_models_")
    for d in ("checkpoints", "loras", "diffusion_models"):
        os.makedirs(os.path.join(shared, d))
    cfg_dir = tempfile.mkdtemp(prefix="smf_desktop_cfg_")
    yml = os.path.join(cfg_dir, "inst-1.yaml")
    with open(yml, "w", encoding="utf-8") as f:
        f.write("# Generated by Comfy Desktop\ncomfy.desktop_0:\n"
                f"  base_path: '{shared}'\n  is_default: true\n"
                "  'checkpoints': 'checkpoints/'\n  'loras': 'loras/'\n  'diffusion_models': 'diffusion_models/'\n"
                "  'Lora': 'Lora/'\n  'StableDiffusion': 'StableDiffusion/'\n")  # SM names whose folders are gone
    # Comfy Desktop passes its file with --extra-model-paths-config
    cli = types.ModuleType("comfy.cli_args")
    cli.args = types.SimpleNamespace(extra_model_paths_config=[[yml]])
    sys.modules["comfy"] = types.ModuleType("comfy")
    sys.modules["comfy.cli_args"] = cli
    smf = T.load_smf(base, user)

    info = smf.paths.sm_info()
    check(info["mode"] == "desktop" and os.path.normcase(info["models_root"]) == os.path.normcase(shared),
          f"Comfy Desktop's default models folder is the shared folder ({info['mode']}, {info['models_root']})")
    sd = smf.config.shared_dir()
    check(sd and os.path.normcase(sd) == os.path.normcase(os.path.join(shared, ".sm_model_fetcher")), f"shared data lives there ({sd})")
    d, is_shared = smf.paths.dest_dir("loras")
    check(os.path.normcase(d) == os.path.normcase(os.path.join(shared, "loras")) and is_shared,
          f"LoRA downloads go to its loras folder, not a missing 'Lora' ({d})")
    d, _ = smf.paths.dest_dir("checkpoints")
    check(os.path.normcase(d) == os.path.normcase(os.path.join(shared, "checkpoints")), f"checkpoints too ({d})")

    # set by hand
    other = tempfile.mkdtemp(prefix="smf_manual_models_")
    smf.config.save({"models_root": other})
    info = smf.paths.sm_info()
    check(info["mode"] == "manual" and os.path.normcase(info["models_root"]) == os.path.normcase(other), "a folder set in Settings wins")
    check(os.path.normcase(smf.config.shared_dir()) == os.path.normcase(os.path.join(other, ".sm_model_fetcher")), "…and the shared data follows it")
    check("models_root" not in smf.config.read_json("config.json", {}), "the setting stays with this install (not in the shared config)")
    smf.config.save({"models_root": os.path.join(other, "missing")})
    check(smf.paths.sm_info()["mode"] == "desktop", "a folder that doesn't exist is ignored")
    smf.config.save({"models_root": ""})
    check(smf.paths.sm_info()["mode"] == "desktop", "cleared: found automatically again")

    for p in (shared, cfg_dir, other):
        shutil.rmtree(p, ignore_errors=True)
    sys.modules.pop("comfy.cli_args", None)
    sys.modules.pop("comfy", None)
    print("\nFAILED: %d" % check.failed if check.failed else "\nALL PASSED")
    return 1 if check.failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
